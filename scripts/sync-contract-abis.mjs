import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(scriptDir, '..');
const hardhatRoot = resolve(projectRoot, '../cactusNFT');
const outputDir = resolve(
  projectRoot,
  'libs/blockchain/src/abis',
);

const contracts = [
  {
    artifact: 'artifacts/contracts/Cactus721.sol/Cactus721.json',
    output: 'cactus721.abi.ts',
    exportName: 'CACTUS_721_ABI',
  },
  {
    artifact: 'artifacts/contracts/Seed721.sol/Seed721.json',
    output: 'seed721.abi.ts',
    exportName: 'SEED_721_ABI',
  },
  {
    artifact:
      'artifacts/contracts/CactusBreeding.sol/CactusBreeding.json',
    output: 'cactus-breeding.abi.ts',
    exportName: 'CACTUS_BREEDING_ABI',
  },
  {
    artifact:
      'artifacts/contracts/CactusGermination.sol/CactusGermination.json',
    output: 'cactus-germination.abi.ts',
    exportName: 'CACTUS_GERMINATION_ABI',
  },
  {
    artifact: 'artifacts/contracts/MockVRF.sol/MockVRF.json',
    output: 'mock-vrf.abi.ts',
    exportName: 'MOCK_VRF_ABI',
  },
];

await mkdir(outputDir, { recursive: true });

for (const contract of contracts) {
  const artifactPath = resolve(hardhatRoot, contract.artifact);
  const artifact = JSON.parse(await readFile(artifactPath, 'utf8'));

  if (!Array.isArray(artifact.abi)) {
    throw new Error(`Artifact does not contain ABI array: ${artifactPath}`);
  }

  const outputPath = resolve(outputDir, contract.output);
  const source = [
    '/* Autogenerated by scripts/sync-contract-abis.mjs. */',
    `export const ${contract.exportName} = ${JSON.stringify(
      artifact.abi,
      null,
      2,
    )} as const;`,
    '',
  ].join('\n');

  await writeFile(outputPath, source);
  console.log(`Synced ${contract.output}`);
}
